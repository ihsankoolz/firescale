//! Tests for `agent-ready/agent-skills`.

use firescale_core::model::{Diagnostic, Fixable};
use firescale_core::rule::{BuiltinRule, Options};
use firescale_core::testing::{Fixture, Track};

use super::{installed_skill, skill_name, AgentSkills, ID, SKILL_DIRS};

fn check(fixture: &Fixture) -> Vec<Diagnostic> {
    fixture.check(&AgentSkills, &Options::new()).unwrap()
}

fn fix(fixture: &Fixture) -> Vec<String> {
    fixture
        .fix(&AgentSkills, &Options::new())
        .unwrap()
        .changed_files
}

const CONFIG: &str = "{ \"packs\": [\"core\", \"agent-ready\"], \"rules\": { \"core/scripts-present\": \"off\" } }\n";

#[test]
fn meta_matches_the_spec() {
    let meta = AgentSkills.meta();
    assert_eq!(meta.id, ID);
    assert!(meta.has_fix);
}

#[test]
fn an_installed_skill_is_named_after_its_folder_and_says_it_is_generated() {
    let source =
        "---\nname: no-committed-env\ndescription: Fixes it.\n---\n\n# core/no-committed-env\n";
    let text = installed_skill(source, "core/no-committed-env");
    assert_eq!(
        skill_name("core/no-committed-env"),
        "firescale-core-no-committed-env"
    );
    assert!(text.starts_with("---\nname: firescale-core-no-committed-env\ndescription: Fixes it.\n---\n<!-- Generated by firescale from the rule core/no-committed-env."));
    assert!(text.ends_with("\n# core/no-committed-env\n"));
}

mod failing_repo {
    use super::*;

    #[test]
    fn each_agent_folder_without_the_skills_is_one_finding() {
        let f = Fixture::new(&[("firescale.config.json", CONFIG)], Track::None).unwrap();
        let found = check(&f);
        let files: Vec<&str> = found.iter().map(|d| d.file.as_str()).collect();
        assert_eq!(
            files,
            [".agents/skills/", ".claude/skills/", ".cursor/skills/"]
        );
        assert!(found.iter().all(|d| d.fixable == Fixable::Deterministic));
    }

    #[test]
    fn a_skill_of_your_own_at_the_same_path_is_left_alone() {
        let mine = "---\nname: firescale-core-ci-exists\ndescription: mine\n---\nours\n";
        let f = Fixture::new(
            &[
                ("firescale.config.json", CONFIG),
                (".claude/skills/firescale-core-ci-exists/SKILL.md", mine),
            ],
            Track::None,
        )
        .unwrap();
        fix(&f);
        assert_eq!(
            f.read(".claude/skills/firescale-core-ci-exists/SKILL.md")
                .unwrap(),
            mine
        );
        let manual: Vec<Diagnostic> = check(&f)
            .into_iter()
            .filter(|d| d.fixable == Fixable::Manual)
            .collect();
        assert_eq!(manual.len(), 1);
    }
}

mod fixed_repo {
    use super::*;

    #[test]
    fn every_enabled_rule_gets_a_skill_for_each_agent_and_a_second_run_changes_nothing() {
        let f = Fixture::new(&[("firescale.config.json", CONFIG)], Track::None).unwrap();
        let written = fix(&f);
        // 7 core rules (one is off) and 6 agent-ready rules, for 3 agents.
        assert_eq!(written.len(), 13 * SKILL_DIRS.len());
        assert!(f
            .read(".agents/skills/firescale-agent-ready-agents-md/SKILL.md")
            .is_some());
        assert!(f
            .read(".cursor/skills/firescale-core-scripts-present/SKILL.md")
            .is_none());
        assert!(check(&f).is_empty());
        assert!(fix(&f).is_empty());
    }

    #[test]
    fn a_generated_skill_that_drifted_is_written_again() {
        let f = Fixture::new(&[("firescale.config.json", CONFIG)], Track::None).unwrap();
        fix(&f);
        let file = ".claude/skills/firescale-core-ci-exists/SKILL.md";
        let good = f.read(file).unwrap();
        std::fs::write(
            f.root().join(file),
            good.replace("## Manual fix", "## Edited"),
        )
        .unwrap();
        assert_eq!(check(&f).len(), 1);
        assert_eq!(fix(&f), [file]);
        assert_eq!(f.read(file).unwrap(), good);
    }
}
